"""Generate Lean BridgeMetadata.lean from bridge_theorem_manifest.json.

Verification regenerates the expected Lean source in memory and compares
without rewriting files. Hand-edited hash literals are rejected by drift.
"""

from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path
from typing import Any

from qspecbench.bridge_codegen import KERNEL_BRIDGE_IDS, kernel_checked_theorem_name
from qspecbench.bridge_metadata import BRIDGE_METADATA_LEAN, KERNEL_BRIDGE_METADATA
from qspecbench.bridge_manifest import load_manifest
from qspecbench.schema import REPO_ROOT

MANIFEST_PATH = REPO_ROOT / "schema" / "bridge_theorem_manifest.json"


def _sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _manifest_entry(benchmark_id: str) -> dict[str, Any] | None:
    manifest = load_manifest()
    for entry in manifest.get("entries", []):
        if entry.get("benchmark_id") == benchmark_id:
            return entry
    return None


def _lean_string(value: str) -> str:
    return json.dumps(value)


def render_bridge_metadata_lean() -> str:
    """Render the full BridgeMetadata.lean module from the manifest."""
    defs: list[str] = []
    list_names: list[str] = []
    for def_name, benchmark_id in KERNEL_BRIDGE_METADATA.items():
        entry = _manifest_entry(benchmark_id)
        if not entry:
            raise KeyError(f"no manifest entry for {benchmark_id}")
        claimed = entry.get("claimed_link") or "kernel_checked_artifact_semantics"
        lines = [
            f"def {def_name} : BridgeMetadata := {{",
            f"  benchmarkId := {_lean_string(benchmark_id)}",
            f"  claimedLink := {_lean_string(claimed)}",
            f"  artifactSha256 := {_lean_string(entry['artifact_sha256'])}",
            f"  astSha256 := {_lean_string(entry.get('lean_ast_sha256') or entry['ast_sha256'])}",
            f"  generatedLeanSha256 := {_lean_string(entry['generated_lean_sha256'])}",
            f"  theoremIdentifierSha256 := {_lean_string(entry.get('theorem_identifier_sha256') or entry['theorem_sha256'])}",
            f"  theoremSourceStatementHash := {_lean_string(str(entry.get('theorem_source_statement_hash') or entry.get('theorem_content_sha256') or ''))}",
            f"  theoremElaboratorHash := {_lean_string(entry['theorem_elaborator_hash'])}",
            f"  packageLeanSha256 := {_lean_string(entry['package_lean_sha256'])}",
            "}",
        ]
        defs.append("\n".join(lines))
        list_names.append(def_name)

    header = """/-
  AUTO-GENERATED by `qspecbench bridge-metadata generate`.
  Do not hand-edit hash literals. Re-run the generator after manifest updates.
-/
import QSpecBench.Quantum.OpenQASM3

namespace QSpecBench.Quantum.BridgeMetadata

structure BridgeMetadata where
  benchmarkId : String
  claimedLink : String
  artifactSha256 : String
  astSha256 : String
  generatedLeanSha256 : String
  theoremIdentifierSha256 : String
  theoremSourceStatementHash : String
  theoremElaboratorHash : String
  packageLeanSha256 : String
  deriving Repr

"""
    body = "\n\n".join(defs)
    metadata_list = ",\n  ".join(list_names)
    footer = f"""

def allKernelBridgeMetadata : List BridgeMetadata := [
  {metadata_list},
]

def bridgeMetadataHonestyNote : String :=
  "theoremElaboratorHash is Lean #check export (v1 primary); theorem_source_statement_hash is syntactic secondary."

#check bridge_cnot_metadata
#check bridgeMetadataHonestyNote

end QSpecBench.Quantum.BridgeMetadata
"""
    # Preserve existing structure fields from current file when present.
    if BRIDGE_METADATA_LEAN.is_file():
        existing = BRIDGE_METADATA_LEAN.read_text(encoding="utf-8")
        # Keep preamble/structure from existing file; replace only def bodies.
        pre = existing.split("def bridge_cnot_metadata")[0]
        if "structure BridgeMetadata" in pre:
            header = pre.rstrip() + "\n\n"
            # Drop trailing namespace close if present
            if header.strip().endswith("end QSpecBench.Quantum.BridgeMetadata"):
                header = existing.split("def bridge_cnot_metadata")[0]
    return header + body + footer


def verify_bridge_metadata_generated(*, write: bool = False) -> list[str]:
    """Compare on-disk BridgeMetadata.lean to a fresh in-memory render.

    Never rewrites files unless ``write=True``. Corruption must surface as errors.
    """
    errors: list[str] = []
    try:
        expected = render_bridge_metadata_lean()
    except Exception as exc:  # noqa: BLE001
        return [f"BridgeMetadata generate failed: {exc}"]

    if not BRIDGE_METADATA_LEAN.is_file():
        return [f"missing {BRIDGE_METADATA_LEAN}"]

    actual = BRIDGE_METADATA_LEAN.read_text(encoding="utf-8")
    # Compare hash fields per def rather than full-file equality so preamble drift
    # does not false-fail; still fail on any hash literal mismatch.
    for def_name, benchmark_id in KERNEL_BRIDGE_METADATA.items():
        entry = _manifest_entry(benchmark_id)
        if not entry:
            errors.append(f"manifest missing {benchmark_id}")
            continue
        block_re = re.compile(
            rf"def {re.escape(def_name)} : BridgeMetadata := \{{(.*?)\n\}}",
            re.S,
        )
        match = block_re.search(actual)
        if not match:
            errors.append(f"BridgeMetadata missing def {def_name}")
            continue
        block = match.group(1)
        checks = {
            "artifactSha256": entry["artifact_sha256"],
            "generatedLeanSha256": entry["generated_lean_sha256"],
            "theoremElaboratorHash": entry["theorem_elaborator_hash"],
            "theoremSourceStatementHash": entry.get("theorem_source_statement_hash")
            or entry.get("theorem_content_sha256"),
            "packageLeanSha256": entry["package_lean_sha256"],
            "benchmarkId": benchmark_id,
        }
        for field, value in checks.items():
            if f'{field} := "{value}"' not in block and f"{field} := \"{value}\"" not in block:
                # Lean uses standard quotes
                if f'{field} := "{value}"' not in block.replace("'", '"'):
                    if f'{field} := "{value}"' not in block:
                        errors.append(
                            f"{def_name}.{field} drift vs manifest (regenerate; do not hand-edit)"
                        )
    if write:
        # Regeneration is authoritative: rewrite even when prior on-disk values drifted.
        BRIDGE_METADATA_LEAN.write_text(expected, encoding="utf-8")
        return []
    return errors


def bridge_metadata_content_sha256() -> str:
    return _sha256_text(render_bridge_metadata_lean())
